def grid(w, h, text):
    rows = [r for r in text.strip('\n').split('\n')]
    assert len(rows) == h, (len(rows), h)
    for i, r in enumerate(rows):
        assert len(r) == w, (i, len(r), w, r)
    return [list(r) for r in rows]


def outline(g):
    h, w = len(g), len(g[0])
    out = [row[:] for row in g]
    for y in range(h):
        for x in range(w):
            if g[y][x] != '.':
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < w and 0 <= ny < h and g[ny][nx] != '.':
                    out[y][x] = '#'
                    break
    return out


def render(g, scale=SCALE):
    h, w = len(g), len(g[0])
    img = Image.new('RGBA', (w * scale, h * scale), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch == '.':
                continue
            c = PAL[ch]
            rgba = tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) + (255,)
            for i in range(scale):
                for j in range(scale):
                    px[x * scale + i, y * scale + j] = rgba
    return img


if __name__ == '__main__':
    OUT.mkdir(parents=True, exist_ok=True)
    imgs = []
    for name, (w, h, text) in ART.items():
        img = render(outline(grid(w, h, text)))
        img.save(OUT / f'decor-{name}.png')
        imgs.append(img)
    # 검수용: 정원 바탕색 위에 2배로
    sheet = Image.new('RGBA', (8 * 216, 232), '#F8FDE6')
    for i, img in enumerate(imgs):
        big = img.resize((img.width * 2, img.height * 2), Image.NEAREST)
        sheet.alpha_composite(big, (i * 216 + (216 - big.width) // 2, 212 - big.height))
    Path('test-results').mkdir(exist_ok=True)
    sheet.convert('RGB').save('test-results/decor-sheet.png')
    print('ok', [p.name for p in sorted(OUT.glob('*.png'))])
